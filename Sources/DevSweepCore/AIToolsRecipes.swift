import Foundation

/// An Electron-based editor or AI app that keeps caches and state in ~/Library/Application Support/<folder>.
struct ElectronApp: Sendable {
    let name: String
    let supportFolder: String
    /// Substrings of a command line that mean the app is running.
    let runningMarkers: [String]
    /// Extra home-relative folders with re-downloadable extensions.
    let disabledExtensionsDir: String?

    static let all: [ElectronApp] = [
        ElectronApp(name: "Cursor", supportFolder: "Cursor",
                    runningMarkers: ["Cursor.app/Contents/MacOS/", "Cursor 3.app/Contents/MacOS/"],
                    disabledExtensionsDir: ".cursor/extensions-disabled"),
        ElectronApp(name: "VS Code", supportFolder: "Code",
                    runningMarkers: ["Visual Studio Code.app/Contents/MacOS/"], disabledExtensionsDir: nil),
        ElectronApp(name: "Windsurf", supportFolder: "Windsurf",
                    runningMarkers: ["Windsurf.app/Contents/MacOS/"], disabledExtensionsDir: nil),
        ElectronApp(name: "Claude", supportFolder: "Claude",
                    runningMarkers: ["Claude.app/Contents/MacOS/Claude"], disabledExtensionsDir: nil),
    ]

    /// Chromium/Electron folders that the app recreates on its own.
    static let cacheFolders = ["Cache", "Code Cache", "GPUCache", "CachedData", "CachedExtensionVSIXs", "DawnCache",
                               "DawnGraphiteCache", "DawnWebGPUCache", "GraphiteDawnCache", "ShaderCache", "logs",
                               "Crashpad"]

    func isRunning(_ s: SystemSnapshot) -> Bool { runningMarkers.contains { s.anyRunning(containing: $0) } }
}

struct AIToolsRecipe: Recipe {
    let id = "ai-tools"

    func discover(_ ctx: ScanContext) async -> [Item] {
        var items: [Item] = []
        for app in ElectronApp.all {
            items += await appItems(app, ctx)
        }
        items += await ollamaItems(ctx)
        return items
    }

    private func appItems(_ app: ElectronApp, _ ctx: ScanContext) async -> [Item] {
        let fm = FileManager.default
        let support = ctx.home.appendingPathComponent("Library/Application Support/\(app.supportFolder)")
        guard fm.isDirectory(support) else { return [] }
        let running = app.isRunning(ctx.snapshot)
        let quit = running ? "Quit \(app.name) to clean this" : nil
        var items: [Item] = []

        func add(_ key: String, _ name: String, _ detail: String, _ paths: [URL], _ tier: Tier, _ loss: String,
                 protection: String?) async {
            let existing = paths.filter { fm.fileExists(atPath: $0.path) }
            guard !existing.isEmpty else { return }
            let size = await FileSize.measure(existing).values.reduce(0, +)
            items.append(Item(recipeID: id, key: "\(app.supportFolder):\(key)", ecosystem: .aiTools, tier: tier,
                              name: name, detail: detail, paths: existing, size: size, lossNote: loss,
                              protection: protection,
                              lastUsed: existing.compactMap { fm.modificationDate($0) }.max()))
        }

        // Caches: always regenerated by the app.
        await add("caches", "\(app.name) caches", "Browser caches, compiled code, GPU shaders and logs",
                  ElectronApp.cacheFolders.map { support.appendingPathComponent($0) }, .rebuilds,
                  "\(app.name) rebuilds these on its next launch, which may be a little slower once.", protection: quit)

        // VS Code family: chat, agent and app state.
        let globalDB = support.appendingPathComponent("User/globalStorage/state.vscdb")
        if fm.fileExists(atPath: globalDB.path) {
            let db = ["", "-wal", "-shm", ".backup"].map { URL(fileURLWithPath: globalDB.path + $0) }
            // Compacting only helps when the database has free pages; say how much, so nobody hopes for more.
            let reclaimable = Self.sqliteFreeBytes(globalDB)
            let detail = reclaimable.map { "User/globalStorage/state.vscdb · compacting would free only \(ByteFormat.string($0))" }
                ?? "User/globalStorage/state.vscdb"
            await add("state-db", "\(app.name) chat and app state", detail, db, .hasData,
                      "All \(app.name) chat and agent history, plus app state such as recent projects and possibly your sign-in. settings.json and keybindings are kept. To shrink it without losing everything, delete old chats inside \(app.name).",
                      protection: quit)
        }
        let workspaces = support.appendingPathComponent("User/workspaceStorage")
        if fm.isDirectory(workspaces) {
            let all = fm.subdirectories(of: workspaces)
            let orphaned = all.filter { Self.workspaceFolderIsGone($0) }
            await add("workspaces-orphaned", "\(app.name) state for deleted folders",
                      "\(orphaned.count) workspace(s) whose folder no longer exists", orphaned, .hasData,
                      "Per-project chat history and editor state for folders that no longer exist on this Mac.",
                      protection: quit)
        }
        await add("history", "\(app.name) local file history", "User/History",
                  [support.appendingPathComponent("User/History")], .hasData,
                  "Earlier versions of files you edited, as shown in \(app.name)'s Timeline view.", protection: quit)
        if let dir = app.disabledExtensionsDir {
            await add("extensions-disabled", "\(app.name) disabled extensions", "~/\(dir)",
                      [ctx.home.appendingPathComponent(dir)], .redownload,
                      "Extensions you turned off. Reinstalled from the marketplace if you enable them again.",
                      protection: quit)
        }

        // Claude desktop specifics.
        if app.supportFolder == "Claude" {
            await add("vm-bundles", "Claude VM image", "vm_bundles · used by agent tasks that run in a VM",
                      [support.appendingPathComponent("vm_bundles")], .redownload,
                      "Claude downloads the VM image again the next time it needs one (several GB).", protection: quit)
            await add("scratch", "Claude scratch workspaces", "scratch-workspaces",
                      [support.appendingPathComponent("scratch-workspaces")], .hasData,
                      "Temporary working folders from Claude sessions, including any files created there.",
                      protection: quit)
            for version in fm.subdirectories(of: support.appendingPathComponent("claude-code")) {
                let v = version.lastPathComponent
                let inUse = ctx.snapshot.anyRunning(containing: "/claude-code/\(v)/")
                await add("claude-code-\(v)", "Claude Code \(v)", inUse ? "Version in use" : "Older version, not in use",
                          [version], .redownload, "Downloaded again automatically if this version is needed.",
                          protection: inUse ? "This version is running" : nil)
            }
        }
        return items
    }

    /// Free pages × page size, read-only and instant (PRAGMA only). Nil for small or unreadable files.
    static func sqliteFreeBytes(_ db: URL) -> Int64? {
        guard let size = (try? db.resourceValues(forKeys: [.fileSizeKey]))?.fileSize, size > 100_000_000 else { return nil }
        let r = Shell.run("/usr/bin/sqlite3", ["file:\(db.path)?mode=ro", "PRAGMA page_size; PRAGMA freelist_count;"],
                          timeout: 10)
        let nums = r.stdout.split(whereSeparator: \.isNewline).compactMap { Int64($0) }
        guard r.ok, nums.count == 2 else { return nil }
        return nums[0] * nums[1]
    }

    /// workspaceStorage/<hash>/workspace.json points at the folder: {"folder": "file:///Users/..."}.
    static func workspaceFolderIsGone(_ dir: URL) -> Bool {
        guard let data = try? Data(contentsOf: dir.appendingPathComponent("workspace.json")),
              let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else { return false }
        guard let s = (obj["folder"] ?? obj["workspace"]) as? String, let url = URL(string: s), url.isFileURL else {
            return false  // remote or unknown workspaces are never treated as gone
        }
        return !FileManager.default.fileExists(atPath: url.path)
    }

    static let ollamaBinaries = ["/opt/homebrew/bin/ollama", "/usr/local/bin/ollama",
                                 "/Applications/Ollama.app/Contents/Resources/ollama"]

    private func ollamaItems(_ ctx: ScanContext) async -> [Item] {
        let fm = FileManager.default
        let models = ctx.home.appendingPathComponent(".ollama/models")
        guard fm.isDirectory(models) else { return [] }
        let manifests = Self.ollamaManifests(models.appendingPathComponent("manifests"))
        let binary = Self.ollamaBinaries.first { fm.isExecutableFile(atPath: $0) }
        let running = ctx.snapshot.anyRunning(containing: "ollama serve") || ctx.snapshot.anyRunning(containing: "Ollama.app")

        guard let binary else {
            // Ollama itself is gone: its models cannot be used by anything.
            let paths = [models.appendingPathComponent("blobs"), models.appendingPathComponent("manifests")]
                .filter { fm.fileExists(atPath: $0.path) }
            let size = await FileSize.measure(paths).values.reduce(0, +)
            let names = manifests.map(\.name).joined(separator: ", ")
            return [Item(recipeID: id, key: "ollama-orphaned", ecosystem: .aiTools, tier: .redownload,
                         name: "Ollama models", detail: "\(names.isEmpty ? "Models" : names) · Ollama is not installed",
                         paths: paths, size: size,
                         lossNote: "The downloaded models. Ollama is no longer installed, so nothing can use them; if you reinstall it, `ollama pull` downloads them again.",
                         lastUsed: fm.modificationDate(models))]
        }
        return manifests.map { m in
            Item(recipeID: id, key: "ollama:\(m.name)", ecosystem: .aiTools, tier: .redownload,
                 name: "Ollama model \(m.name)", detail: "~/.ollama/models", paths: [], size: m.size,
                 action: .command([binary, "rm", m.name]),
                 lossNote: "Downloaded again with `ollama pull \(m.name)` when you need it.",
                 protection: running ? nil : "Start Ollama first: ollama rm needs it running", lastUsed: m.modified)
        }
    }

    struct OllamaManifest { let name: String; let size: Int64; let modified: Date? }

    /// manifests/<registry>/<namespace>/<model>/<tag> JSON with layer sizes.
    static func ollamaManifests(_ root: URL) -> [OllamaManifest] {
        let fm = FileManager.default
        guard let e = fm.enumerator(at: root, includingPropertiesForKeys: [.isRegularFileKey]) else { return [] }
        var out: [OllamaManifest] = []
        for case let f as URL in e {
            guard (try? f.resourceValues(forKeys: [.isRegularFileKey]))?.isRegularFile == true,
                  let data = try? Data(contentsOf: f),
                  let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else { continue }
            let layers = (obj["layers"] as? [[String: Any]]) ?? []
            let size = layers.compactMap { ($0["size"] as? NSNumber)?.int64Value }.reduce(0, +)
            let parts = f.pathComponents.suffix(3)  // namespace, model, tag
            guard parts.count == 3 else { continue }
            let arr = Array(parts)
            let base = arr[0] == "library" ? arr[1] : "\(arr[0])/\(arr[1])"
            out.append(OllamaManifest(name: "\(base):\(arr[2])", size: size, modified: fm.modificationDate(f)))
        }
        return out.sorted { $0.name < $1.name }
    }
}
